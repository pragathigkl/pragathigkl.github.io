async function fetchRepoFolderFiles(folder, extRegex, forceRefresh=false){
 const cacheKey=`pragathi_dir_${folder}_v1`;
 if(!forceRefresh){
  try{
   const raw=sessionStorage.getItem(cacheKey);
   if(raw){
    const parsed=JSON.parse(raw);
    if(parsed&&Date.now()-parsed.ts<180000&&Array.isArray(parsed.items))return parsed.items;
   }
  }catch{}
 }
 let items=[];
 try{
  const r=await fetch(`https://api.github.com/repos/${C.repo}/contents/${folder}?_t=${Date.now()}`,{headers:{Accept:"application/vnd.github+json"}});
  if(r.ok){
   const arr=await r.json();
   if(Array.isArray(arr)){
    items=arr
     .filter(f=>f.type==="file"&&extRegex.test(f.name))
     .map(f=>({name:f.name,title:cleanFileLabel(f.name),url:`${folder}/${encodeURIComponent(f.name)}`,size:f.size||0}));
   }
  }
 }catch{}
 try{
  const r2=await fetch(`${folder}/list.json?_t=${Date.now()}`);
  if(r2.ok){
   const list=await r2.json();
   if(Array.isArray(list)){
    const seen=new Set(items.map(i=>i.name.toLowerCase()));
    for(const entry of list){
     const fname=typeof entry==="string"?entry:(entry.file||entry.name||"");
     if(!fname||!extRegex.test(fname)||seen.has(fname.toLowerCase()))continue;
     seen.add(fname.toLowerCase());
     items.push({name:fname,title:(typeof entry==="object"&&entry.title)?entry.title:cleanFileLabel(fname),url:`${folder}/${encodeURIComponent(fname)}`,size:entry.size||0});
    }
   }
  }
 }catch{}
 items.sort((a,b)=>b.name.localeCompare(a.name,undefined,{numeric:true,sensitivity:"base"}));
 try{sessionStorage.setItem(cacheKey,JSON.stringify({ts:Date.now(),items}))}catch{}
 return items;
}

